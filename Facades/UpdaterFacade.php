<?php
namespace axenox\PackageManager\Facades;

use Psr\Http\Message\ResponseInterface;
use Psr\Http\Message\ServerRequestInterface;
use exface\Core\Facades\AbstractHttpFacade\AbstractHttpFacade;
use exface\Core\DataTypes\StringDataType;
use GuzzleHttp\Psr7\Response;
use exface\Core\Facades\AbstractHttpFacade\Middleware\AuthenticationMiddleware;
use axenox\PackageManager\Common\Updater\UploadedRelease;
use axenox\PackageManager\Common\Updater\ReleaseLog;
use axenox\PackageManager\Common\Updater\SelfUpdateInstaller;
use axenox\PackageManager\Common\Updater\ReleaseLogEntry;
use axenox\PackageManager\Common\Updater\ZipFile;
use axenox\PackageManager\Common\Updater\NativePushReceiver;

/**
 * HTTP facade to allow remote updates (deployment) on this server
 * 
 * @author Thomas Ressel
 *
 */
class UpdaterFacade extends AbstractHttpFacade
{
    /**
     *
     * {@inheritDoc}
     * @see \exface\Core\Facades\AbstractHttpFacade\AbstractHttpFacade::createResponse()
     */
    protected function createResponse(ServerRequestInterface $request) : ResponseInterface
    {
        $uri = $request->getUri();
        $path = $uri->getPath();
        $pathInFacade = mb_strtolower(StringDataType::substringAfter($path, $this->getUrlRouteDefault() . '/'));
        $headers = $this->buildHeadersCommon();
                
        switch (true) {
            // Generated by GitHub Copilot - Nov-05-2026
            case $pathInFacade === 'native-push':
                return $this->createNativePushResponse($request);
            
            case $pathInFacade === 'upload-file':
                
                // Move uploaded files to uploadPath
                $uploader = new UploadedRelease($request);
                $uploadPath = __DIR__ . '/../../../../Upload/';
                $uploader->moveUploadedFiles($uploadPath);
                $log = new ReleaseLog($this->getWorkbench());
                // fills logFile with information about the upload
                $releaseLogEntry = new ReleaseLogEntry($log);
                $releaseLogEntry->fillLogFileFormatUpload($uploader);
                
                // install
                $installationFilePath = $uploadPath . $uploader->getInstallationFileName();
                $selfUpdateInstaller = new SelfUpdateInstaller($installationFilePath, $this->getWorkbench()->filemanager()->getPathToCacheFolder());
                // fills logFile with information about the installation
                $releaseLogEntry->fillLogFileFormatInstallation($selfUpdateInstaller);
                
                // logfile: generates logEntry from LogFileFormat
                $releaseLogEntry->createEntry();
                
                // update release file if installation was successful
                if($selfUpdateInstaller->getInstallationSuccess()) {
                    $releaseLogEntry->addNewDeployment($uploader->getTimestamp(), $uploader->getInstallationFileName());
                }
                $headers['Content-Type'] = 'text/plain-stream';
                return new Response(200, $headers, $releaseLogEntry->getEntry());
                
                /*
                // Simulate installation with sleep-timer
                $generator = function ($bytes) use($output) {
                    yield $output;
                    for ($i = 0; $i < $bytes; $i++) {
                        sleep(1);
                        yield '.'.$i.'.';
                        ob_flush();
                        flush();
                    }
                };
                
                $stream = new IteratorStream($generator(5));
                $stream = new IteratorStream($installer->install());
                */
                
            case $pathInFacade === 'status':
                $releaseLog = new ReleaseLog($this->getWorkbench());
                $output = "Last Deployment: " . $releaseLog->getLatestDeployment() . PHP_EOL. PHP_EOL;
                $output .= $releaseLog->getLatestLog();
                $headers['Content-Type'] = 'text/plain-stream';
                return new Response(200, $headers, $output);
                
            // Shows log-entries for all uploaded files
            case $pathInFacade === 'log':
                // Gets log-entries for all uploaded files as Json
                $releaseLog = new ReleaseLog($this->getWorkbench());
                $headers['Content-Type'] = 'application/json';
                return new Response(200, $headers, json_encode($releaseLog->getLogEntries(), JSON_PRETTY_PRINT));
                
            case $pathInFacade === 'zip':
                $zip = new ZipFile();
                $zip->zip();

            // Search for pathInFacade in log-directory
            default:
                $releaseLog = new ReleaseLog($this->getWorkbench());
                if($releaseLog->getLogContent($pathInFacade) !== null) {
                    $headers['Content-Type'] = 'text/plain-stream';
                    return new Response(200, $headers, $releaseLog->getLogContent($pathInFacade));
                }
        }
        return new Response(404);
    }

    /**
     * Explicit opt-in and principal allowlist, in addition to Basic auth middleware.
     * No request parameter can configure staging, executable, credentials or limits.
     *
     * @param ServerRequestInterface $request
     * @return ResponseInterface
     */
    protected function createNativePushResponse(ServerRequestInterface $request): ResponseInterface
    {
        $headers = ['Content-Type' => 'application/json', 'Cache-Control' => 'private, no-store'];
        try {
            $config = $this->getApp()->getConfig();
            $token = $this->getWorkbench()->getSecurity()->getAuthenticatedToken();
            $users = $config->getOption('UPDATER.NATIVE_PUSH.ALLOWED_USERS');
            if ($users instanceof \exface\Core\CommonLogic\UxonObject) {
                $users = $users->toArray();
            }
            if ($config->getOption('UPDATER.NATIVE_PUSH.ENABLED') !== true || $token->isAnonymous()
                || ! is_array($users) || ! in_array($token->getUsername(), $users, true)) {
                return new Response(403, $headers, '{"status":90,"error":"Native push is not authorized."}');
            }
            if ($request->getUri()->getScheme() !== 'https') {
                return new Response(400, $headers, '{"status":90,"error":"Native push requires HTTPS."}');
            }
            $staging = (string) $config->getOption('UPDATER.NATIVE_PUSH.STAGING_PATH');
            $base = realpath($this->getWorkbench()->getInstallationPath());
            $resolved = realpath($staging);
            if ($resolved === false || $base === false
                || str_starts_with(strtolower($resolved . DIRECTORY_SEPARATOR), strtolower($base . DIRECTORY_SEPARATOR))) {
                throw new \RuntimeException('Native push staging must be outside the web installation.');
            }
            $receiver = new NativePushReceiver($staging,
                $config->hasOption('UPDATER.NATIVE_PUSH.PHP_EXECUTABLE')
                    ? (string) $config->getOption('UPDATER.NATIVE_PUSH.PHP_EXECUTABLE') : PHP_BINARY);
            return $receiver->receive($request);
        } catch (\Throwable $error) {
            return new Response(503, $headers, '{"status":90,"error":"Native push is disabled or target configuration is unavailable."}');
        }
    }
    
    /**
     *
     * {@inheritDoc}
     * @see \exface\Core\Facades\AbstractHttpFacade\AbstractHttpFacade::getMiddleware()
     */
    protected function getMiddleware() : array
    {
        return array_merge(parent::getMiddleware(), [
            new AuthenticationMiddleware($this, [
                [
                    AuthenticationMiddleware::class, 'extractBasicHttpAuthToken'
                ]
            ])
        ]);
    }
    
    /**
     * 
     * {@inheritDoc}
     * @see \exface\Core\Facades\AbstractHttpFacade\AbstractHttpFacade::getUrlRouteDefault()
     */
    public function getUrlRouteDefault(): string
    {
        return 'api/updater';
    }
    
    protected function printLineDelimiter() : string
    {
        return PHP_EOL . '--------------------------------' . PHP_EOL . PHP_EOL;
    }
}